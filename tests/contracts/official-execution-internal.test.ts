import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import type { ExerciseType } from '../../src/shared/contracts/practice'
import { isExercise } from '../../src/shared/contracts/practice'
import { exercises } from '../fixtures/learning/legacy-exercises'
import { checkExecutionInput, checkExecutionSignature, type ExecutionPlan } from '../../src/main/services/learning/runtime/execution-plan'
import { generateCsharpHarness, generateCsharpSignatureHarness } from '../../src/main/services/learning/runtime/csharp-harness'
import { FixedJavascriptHarness, javascriptInputRequest, javascriptSignaturePreparation } from '../../src/main/services/learning/runtime/javascript-harness'
import type { OfficialCaseObservation, OfficialSettledCaseConsumer } from '../../src/main/services/learning/runtime/official-execution-contracts'

const values = { int32: -2147483648, boolean: false, string: 'x Ω', 'int32[]': [0, -1], 'string[]': ['', 'Ω'], 'int32[][]': [[1, 2], [3, 4]] }
describe('E3-S1 input-only signature seams and legacy compatibility', () => {
  it.each(Object.keys(values) as ExerciseType[])('preserves %s without Expected in either harness', type => {
    const signature = { functionName: 'Echo', parameters: [{ name: 'value', type }], returnType: type }
    const schema = { parameterTypes: [type], returnType: type, sampleCount: 128 }
    const plan: ExecutionPlan = { signature, caseCount: 128, inputAt: () => [values[type]] }
    expect(checkExecutionInput(plan, 127)).toEqual([values[type]])
    expect(() => checkExecutionInput(plan, 128)).toThrow()
    expect(generateCsharpSignatureHarness(signature, schema)).toContain('().@Echo')
    expect(generateCsharpSignatureHarness(signature, schema)).not.toMatch(/expected|visibility|testSetId/)
    expect(JSON.parse(javascriptSignaturePreparation(signature, 128, '/* not evaluated */', schema))).toEqual({ code: '/* not evaluated */', functionName: 'Echo', schema })
    expect(javascriptInputRequest(checkExecutionInput(plan, 127), schema, 127)).toEqual({ protocolVersion: 1, caseIndex: 127, args: [values[type]] })
    expect(() => checkExecutionInput({ ...plan, inputAt: () => [] }, 0)).toThrow()
  })
  it('keeps every public C# generated byte and JavaScript source/request shape compatible', () => {
    for (const exercise of exercises) {
      const schema = { parameterTypes: exercise.parameters.map(p => p.type), returnType: exercise.returnType, sampleCount: exercise.samples.length }
      expect(generateCsharpSignatureHarness(exercise, schema)).toBe(generateCsharpHarness(exercise, schema))
      expect(javascriptSignaturePreparation(exercise, schema.sampleCount, '// fixture', schema)).toBe(JSON.stringify({ code: '// fixture', functionName: exercise.functionName, schema }))
      for (let i = 0; i < schema.sampleCount; i++) expect(javascriptInputRequest(exercise.samples[i].args, schema, i)).toEqual({ protocolVersion: 1, caseIndex: i, args: exercise.samples[i].args })
    }
    expect(FixedJavascriptHarness).toBeTypeOf('function')
  })
  it('retains the public 16-sample cap independently of private counts', () => {
    const exercise = exercises[0]
    expect(isExercise({ ...exercise, samples: Array(16).fill(exercise.samples[0]) })).toBe(true)
    expect(isExercise({ ...exercise, samples: Array(17).fill(exercise.samples[0]) })).toBe(false)
    for (const count of [17, 21, 128]) expect(() => checkExecutionSignature(exercise, count)).not.toThrow()
    for (const count of [0, -1, 1.5, 129, NaN]) expect(() => checkExecutionSignature(exercise, count)).toThrow()
    expect(() => generateCsharpHarness(exercise, { parameterTypes: [], returnType: 'int32', sampleCount: 21 })).toThrow()
  })
  it('rejects signature injection, wrong types, arity and schema disagreement', () => {
    const signature = { functionName: 'Echo', parameters: [{ name: 'value', type: 'int32' as const }], returnType: 'int32' as const }
    const plan: ExecutionPlan = { signature, caseCount: 1, inputAt: () => ['wrong'] }
    expect(() => checkExecutionSignature({ ...signature, functionName: 'Echo();bad' }, 1)).toThrow()
    expect(() => checkExecutionInput(plan, 0)).toThrow()
    expect(() => javascriptInputRequest([1, 2], { parameterTypes: ['int32'], returnType: 'int32', sampleCount: 1 }, 0)).toThrow()
    expect(() => javascriptSignaturePreparation(signature, 21, '', { parameterTypes: ['boolean'], returnType: 'int32', sampleCount: 21 })).toThrow()
  })
  it('defines synchronous private observations without adding public exports or wiring', () => {
    const observations: OfficialCaseObservation[] = [
      { language: 'csharp', caseIndex: 0, process: null, kind: 'RETURNED', actual: 3, stdout: '', stderr: '' },
      { language: 'javascript', caseIndex: 0, process: null, kind: 'USER_EXCEPTION', stdout: '', stderr: '' },
      { language: 'javascript', caseIndex: 0, process: null, kind: 'INVALID_RESULT', stdout: '', stderr: '' },
      { language: 'csharp', caseIndex: 0, process: null, kind: 'PROTOCOL_FAILURE', reason: 'MALFORMED' },
      { language: 'csharp', caseIndex: 0, process: null, kind: 'INFRASTRUCTURE_FAILURE', reason: 'UNKNOWN' },
    ]
    const consumer: OfficialSettledCaseConsumer = () => 'STOP'
    expect(observations.map(consumer)).toEqual(Array(5).fill('STOP'))
    expect(readFileSync('src/shared/contracts/index.ts', 'utf8')).not.toMatch(/official-case-plan|official-execution|execution-plan|execution-json/)
    expect(readFileSync('src/main/services/learning/exercise-service.ts', 'utf8')).not.toMatch(/acquireOfficialCasePlan|OfficialSettledCaseConsumer/)
  })
})
