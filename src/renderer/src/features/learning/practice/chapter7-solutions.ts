// Public-statement content only. Tuples explain individual meaningful source lines;
// bare punctuation rows preserve complete syntax without extra walkthrough steps.
type SourceLine = string | readonly [code: string, explanation: string]
const types: Record<ExerciseType, string> = { int32: 'int', boolean: 'bool', string: 'string', 'int32[]': 'int[]', 'string[]': 'string[]', 'int32[][]': 'int[][]' }
function source(signature: ExerciseSolution['signature'], language: ExerciseLanguage, body: SourceLine[]) {
  const parameters = signature.parameters.map(parameter => language === 'csharp' ? `${types[parameter.type]} ${parameter.name}` : parameter.name).join(', ')
  const jsParameters = signature.parameters.map(parameter => `${parameter.name}: ${parameter.type === 'int32[]' ? 'mảng number nguyên' : 'number nguyên'}`).join(', ')
  const header: SourceLine[] = language === 'csharp' ? [
    ['public class Solution', 'Khai báo lớp Solution công khai theo mẫu C# của IDE; không cần viết Main hoặc chương trình Console.'], '{',
    [`    public ${types[signature.returnType]} ${signature.functionName}(${parameters})`, `Phương thức instance ${signature.functionName} nhận ${parameters} và trả ${types[signature.returnType]}; giữ đúng tên và kiểu tham số của bài.`], '    {',
  ] : [[`function ${signature.functionName}(${parameters}) {`, `Khai báo hàm ${signature.functionName}, nhận ${jsParameters} và trả ${signature.returnType === 'int32[]' ? 'mảng number nguyên' : 'number nguyên'}. IDE truyền tham số; không tự đọc stdin hoặc gọi hàm.`]]
  const indent = language === 'csharp' ? '        ' : '    '
  const rows = [...header, ...body.map<SourceLine>(line => typeof line === 'string' ? indent + line : [indent + line[0], line[1]]),
    ...(language === 'csharp' ? ['    }', '}'] : ['}'])]
  return { code: rows.map(line => typeof line === 'string' ? line : line[0]).join('\n'),
    lines: rows.flatMap((line, index) => typeof line === 'string' ? [] : [{ code: line[0], explanation: line[1], lineNumber: index + 1 }]) }
}
const array = (name: string, target = false): ExerciseSolution['signature']['parameters'] => [
  { name, type: 'int32[]' }, ...(target ? [{ name: 'target', type: 'int32' as const }] : []),
]
function entry(exerciseId: string, signature: ExerciseSolution['signature'], analysis: string[], algorithm: string[], csharp: SourceLine[], javascript: SourceLine[], time: string, space: string): ExerciseSolution {
  return { exerciseId, signature, analysis: [...analysis, 'Chỉ return giá trị hoặc mảng kết quả đúng contract; không đọc/ghi Console hoặc STDIN/STDOUT. Chỉ số mảng tính từ 0 và input tuân theo miền đề bài.'], algorithm,
    languages: { csharp: source(signature, 'csharp', csharp), javascript: source(signature, 'javascript', javascript) }, complexity: { time, space } }
}

